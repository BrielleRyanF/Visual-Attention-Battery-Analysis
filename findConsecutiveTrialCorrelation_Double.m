%Will take trial structure collected from the 
%readAnalayzePlotBehData function and find correlation between trial(N) and
%trial(N+1) in current trial structure for data formatted as a double. Will work for subsets of trials that 
%are not continuous, such as trials of a specific cue length or 
%response type. With these, you could assess the relationship between those trials as long
%as you provide the data as one trial structure
%inputs - 
%   trials: "trials" structure generated by function mentioned above
%   field: the field in the trial structure to compare
%outputs - 
% trialCorrelation: a structure with the fields R representing the correlation between trial(N) and
%trial(N+1) and P, the p value. 
%--------------------------------------------------------------------------

 function trialCorrelation = findConsecutiveTrialCorrelation_Double(trials, field)
 %pull out field
 for i = 1:length(trials)
 myField(i) = trials(i).(field);
 end

 %Compute correlation between trials
 [trialCorrelation.R, trialCorrelation.P] = corr(myField(1:end-1)', myField(2:end)');
 end
